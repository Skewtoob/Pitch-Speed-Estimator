def test_synth_package_clip_through_io_layer():
    """A pitchspeed.synth clip, decoded through pitchspeed.io (first 10 s)."""
    import glob
    cands = sorted(glob.glob(os.path.join(VH.SYNTH_DIR, "suite12", "*side_hs_tff_mpeg2.mpg")))
    if not cands:
        pytest.skip("no pitchspeed.synth suite clip available")
    clip = cands[0]
    from pitchspeed.calib.model import CalibrationFile
    from pitchspeed.io.interlace import SampleSource, detect_scan
    from pitchspeed.io.reader import VideoReader
    from pitchspeed.vision import FinderOptions, PitchFinder
    gt = json.load(open(clip + ".gt.json", encoding="utf-8"))
    cf = CalibrationFile.load(clip + ".calib.json")
    with VideoReader(clip) as r:
        scan = detect_scan(r, override=gt["video"]["field_order"], verify_override=False, use_idet=False)
        src = SampleSource(r, scan)
        calib = cf.segment_calibs()[0]
        f = PitchFinder(calib, scan, src.sample_dt, src.sample_shape, r.get_frame(calib.ref_frame, "gray"),
                        FinderOptions())
        s1 = min(src.n_samples, int(10.0 / src.sample_dt))
        for smp in src.iter_samples(0, s1):
            f.process(smp)
        res = f.finish()
    want = [p for p in gt["pitches"] if p["t_catch"] < 9.5]
    assert want
    for p in want:
        hits = [t for t in res.tracks if abs(t.release.t - p["t_release"]) < 0.05]
        assert hits, f"pitch at {p['t_release']:.2f} s not found"
        assert abs(hits[0].catch.t - p["t_catch"]) < max(0.02, 3 * hits[0].catch.sigma)
    assert len(res.tracks) <= len(want) + 1
