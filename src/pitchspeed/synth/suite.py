"""Stratified suite of synthetic clips + index.csv.

    rows = generate_suite("suite/", n=40, seed=1, jobs=4)

Factors (balanced over the clips, then shuffled independently):
view (side / behind), level (46 ft youth 40-70 mph / 60.5 ft 55-92 mph),
true field order (TFF / BFF; DV is always BFF like real NTSC DV), codec
(mpeg2 / dv / h264 / ffv1).  Continuous factors are Latin-hypercube
stratified: shutter (1/60 .. 1/1000 s, log), luma noise sigma0 (1..6),
camera geometry (side: distance 80-150 ft (46 ft level: 65-120), angle 65-90 deg,
height 3-15 ft; behind: 12-40 ft back, lateral -6..6 ft, height 3-9 ft; all
framable by a <= 55 deg camcorder lens), shake amplitude,
bitrate, fence distance / aperture (behind views).  Some clips get a pan,
a lying field-order flag, no umpire, birds.  `variants=True` also mixes in
progressive30 / progressive60 / blend / field_discard / yadif_bob renders.

Each clip is generated by `generate_clip` in a worker process ('spawn'
context: Windows-safe).  A clip whose GT already exists with the same
seed and config is reused (resume after an interruption).  Failures are
recorded in index.csv with status=error (never silently dropped).
"""
from __future__ import annotations

import concurrent.futures as cf
import copy
import csv
import json
import math
import multiprocessing
import os
import time
import traceback
from typing import Callable, Optional

import numpy as np

from pitchspeed.synth.config import deep_update, resolve_config
from pitchspeed.synth.encode import DEFAULT_EXT
from pitchspeed.synth.gt import calib_path_for, gt_path_for

SUITE_BASE: dict = {
    "duration_s": 24.0,
    "pitches": {"count": 3, "first_t": 2.5, "gap_s": [4.0, 6.0]},
    "calibration": {"click_noise_px": 1.0, "emit_exact": True},
}

INDEX_COLUMNS = ["name", "status", "file", "gt", "calib", "calib_exact", "seed", "view", "level", "distance_ft",
                 "scan", "field_order", "metadata_field_order", "postprocess", "codec", "bitrate_kbps",
                 "shutter_s", "noise_sigma0", "tape", "fence", "fence_blur_px", "cam_distance_ft",
                 "cam_angle_deg", "cam_height_ft", "cam_back_ft", "cam_lateral_ft", "hfov_deg", "shake_amp_deg",
                 "pan", "umpire", "birds", "duration_s", "n_frames", "n_pitches", "speeds_mph", "t_release_s",
                 "warnings", "gen_time_s", "error"]


# ------------------------------------------------------------------ sampling
def _balanced(rng: np.random.Generator, n: int, choices: list, weights: Optional[list] = None) -> list:
    """n items with the given proportions (largest remainders), shuffled."""
    w = np.asarray(weights if weights is not None else [1.0] * len(choices), dtype=float)
    w = w / w.sum()
    cnt = np.floor(w * n).astype(int)
    rem = w * n - cnt
    for i in np.argsort(-rem)[: n - cnt.sum()]:
        cnt[i] += 1
    out = [c for c, k in zip(choices, cnt) for _ in range(k)]
    rng.shuffle(out)
    return out


def _lhs(rng: np.random.Generator, n: int) -> np.ndarray:
    """Latin-hypercube samples in [0, 1): one per stratum, shuffled."""
    return (rng.permutation(n) + rng.random(n)) / n


def _lerp(u: float, lo: float, hi: float) -> float:
    return float(lo + (hi - lo) * u)


def _loglerp(u: float, lo: float, hi: float) -> float:
    return float(math.exp(math.log(lo) + (math.log(hi) - math.log(lo)) * u))


def suite_configs(n: int, seed: int = 1, base: Optional[dict] = None, variants: bool = False) -> list:
    """[(name, partial config)] of a stratified suite (deterministic in seed)."""
    rng = np.random.default_rng(np.random.SeedSequence([int(seed), 77]))
    views = _balanced(rng, n, ["side", "behind"])
    levels = _balanced(rng, n, ["ll", "hs"])
    orders = _balanced(rng, n, ["tff", "bff"])
    codecs = _balanced(rng, n, ["mpeg2", "dv", "h264", "ffv1"], [0.35, 0.30, 0.25, 0.10])
    scans = _balanced(rng, n, ["interlaced", "progressive30", "progressive60", "blend", "field_discard", "yadif_bob"],
                      [0.70, 0.06, 0.06, 0.06, 0.06, 0.06]) if variants else ["interlaced"] * n
    U = {k: _lhs(rng, n) for k in ("shutter", "noise", "g1", "g2", "g3", "shake", "bitrate", "fence", "fnum")}
    out = []
    for i in range(n):
        view, level, fo, codec, scan = views[i], levels[i], orders[i], codecs[i], scans[i]
        if codec == "dv":
            fo = "bff"
        cfg = copy.deepcopy(SUITE_BASE)
        cfg["seed"] = int(seed) * 1000 + i
        cfg["level"] = level
        cam = {"view": view, "side": "1b" if rng.random() < 0.6 else "3b", "fit_margin": _lerp(rng.random(), 0.06, 0.2)}
        if view == "side":                 # ranges a <= 55 deg camcorder lens can frame
            dmin, dmax = (80.0, 150.0) if level == "hs" else (65.0, 120.0)
            cam.update(distance_ft=_lerp(U["g1"][i], dmin, dmax), angle_deg=_lerp(U["g2"][i], 65.0, 90.0),
                       height_ft=_lerp(U["g3"][i], 3.0, 15.0))
        else:
            cam.update(back_ft=_lerp(U["g1"][i], 12.0, 40.0), lateral_ft=_lerp(U["g2"][i], -6.0, 6.0),
                       height_ft=_lerp(U["g3"][i], 3.0, 9.0))
        video = {"field_order": fo, "codec": codec}
        if codec == "mpeg2":
            video["bitrate_kbps"] = int(_lerp(U["bitrate"][i], 2500, 6000))
        elif codec == "h264":
            video["bitrate_kbps"] = int(_lerp(U["bitrate"][i], 800, 3000))
        if codec in ("mpeg2", "h264", "ffv1") and rng.random() < 0.1:
            video["metadata_field_order"] = "bff" if fo == "tff" else "tff"      # a lying flag
        if scan != "interlaced":
            if scan in ("progressive30", "progressive60"):
                video["scan"] = scan
            else:
                video["postprocess"] = scan
        tape = "dv" if codec == "dv" else str(rng.choice(["hi8", "vhs", "none"], p=[0.45, 0.45, 0.10]))
        shake = {"amp_deg": _lerp(U["shake"][i], 0.0, 0.5), "fmax_hz": _lerp(rng.random(), 2.0, 6.0)}
        pan = None
        if rng.random() < 0.15:
            pan = {"t": _lerp(rng.random(), 4.0, 18.0), "dur": _lerp(rng.random(), 0.6, 1.5),
                   "yaw_deg": float(rng.choice([-1, 1]) * _lerp(rng.random(), 2.0, 8.0))}
            shake["pans"] = [pan]
        cfg.update(camera=cam, video=video, tape={"profile": tape}, shake=shake,
                   render={"shutter_s": 1.0 / _loglerp(U["shutter"][i], 60.0, 1000.0)},
                   noise={"sigma0": _lerp(U["noise"][i], 1.0, 6.0)},
                   distractors={"umpire": bool(rng.random() < 0.6), "umpire_x_ft": _lerp(rng.random(), -1.5, 0.5),
                                "batter": bool(rng.random() < 0.8),
                                "birds": int(rng.poisson(0.5))})
        if view == "behind":
            cfg["fence"] = {"dist_ft": _lerp(U["fence"][i], 1.0, 6.0)}
            cfg["camera"]["f_number"] = _lerp(U["fnum"][i], 1.6, 2.8)
        if base:
            deep_update(cfg, copy.deepcopy(base))
        name = f"s{int(seed):03d}_{i:03d}_{view}_{level}_{video.get('postprocess') or video.get('scan', fo)}_{codec}"
        out.append((name, cfg))
    return out


# ------------------------------------------------------------------ rows
def _row_from_gt(name: str, gt: dict, gen_time: float) -> dict:
    cfg = gt["config"]
    cam = cfg["camera"]
    V = gt["video"]
    cal = gt["calibration"]
    p = gt["pitches"]
    return dict(
        name=name, status="ok", file=V["file"], gt=V["file"] + ".gt.json", calib=cal.get("file"),
        calib_exact=cal.get("exact_file", ""), seed=gt["seed"], view=cam["view"], level=gt["level"]["key"],
        distance_ft=gt["level"]["distance_ft"], scan=V["scan"], field_order=V["field_order"] or "",
        metadata_field_order=V["metadata_field_order"], postprocess=V["postprocess"] or "", codec=V["codec"],
        bitrate_kbps=V["bitrate_kbps"] if V["codec"] in ("mpeg2", "h264", "mpeg4") else "",
        shutter_s=f"{cfg['render']['shutter_s']:.6f}", noise_sigma0=f"{cfg['noise']['sigma0']:.2f}",
        tape=cfg["tape"]["profile"], fence=int(bool(gt["camera"]["fence"]["enabled"])),
        fence_blur_px=f"{gt['camera']['fence']['blur_px']:.2f}",
        cam_distance_ft=f"{cam['distance_ft']:.1f}" if cam["view"] == "side" else "",
        cam_angle_deg=f"{cam['angle_deg']:.1f}" if cam["view"] == "side" else "",
        cam_height_ft=f"{cam['height_ft']:.1f}",
        cam_back_ft=f"{cam['back_ft']:.1f}" if cam["view"] == "behind" else "",
        cam_lateral_ft=f"{cam['lateral_ft']:.1f}" if cam["view"] == "behind" else "",
        hfov_deg=f"{gt['camera']['hfov_deg']:.2f}", shake_amp_deg=f"{cfg['shake']['amp_deg']:.3f}",
        pan=int(bool(cfg["shake"].get("pans"))), umpire=int(bool(cfg["distractors"]["umpire"])),
        birds=int(cfg["distractors"]["birds"]), duration_s=cfg["duration_s"], n_frames=V["n_out_frames"],
        n_pitches=len(p), speeds_mph=";".join(f"{x['speed_release_mph']:.2f}" for x in p),
        t_release_s=";".join(f"{x['t_release']:.4f}" for x in p), warnings=" | ".join(gt.get("warnings", [])),
        gen_time_s=f"{gen_time:.1f}", error="")


def _suite_one(args: tuple) -> dict:
    """Worker: generate one clip (or reuse it) and return its index row."""
    name, cfg, path, resume = args
    try:
        import cv2
        cv2.setNumThreads(1)
        gp = gt_path_for(path)
        if resume and os.path.exists(gp) and os.path.exists(path):
            with open(gp, "r", encoding="utf-8") as f:
                old = json.load(f)
            if old.get("config") == json.loads(json.dumps(resolve_config(cfg))):
                return _row_from_gt(name, old, float(old.get("timing", {}).get("total_s", 0.0)))
        from pitchspeed.synth.generate import generate_clip
        t0 = time.perf_counter()
        gt = generate_clip(cfg, path, jobs=1)
        return _row_from_gt(name, gt, time.perf_counter() - t0)
    except Exception as e:                    # noqa: BLE001 - recorded in the index
        tb = traceback.format_exc(limit=3).replace("\n", " / ")
        return dict(name=name, status="error", file=os.path.basename(path), seed=cfg.get("seed"),
                    view=cfg.get("camera", {}).get("view"), error=f"{type(e).__name__}: {e} [{tb[-400:]}]")


def write_index(rows: list, path: str) -> None:
    tmp = path + ".tmp"
    with open(tmp, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=INDEX_COLUMNS, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in INDEX_COLUMNS})
    os.replace(tmp, path)


def generate_suite(out_dir: str, n: int = 40, seed: int = 1, jobs: int = 1, base: Optional[dict] = None,
                   variants: bool = False, resume: bool = True,
                   progress: Optional[Callable[[str], None]] = None) -> list:
    """Generate n clips into out_dir (+ index.csv); returns the index rows (in suite order)."""
    os.makedirs(out_dir, exist_ok=True)
    configs = suite_configs(n, seed, base, variants)
    tasks = []
    for name, cfg in configs:
        codec = cfg.get("video", {}).get("codec", "mpeg2")
        tasks.append((name, cfg, os.path.join(out_dir, name + DEFAULT_EXT.get(codec, ".mkv")), resume))
    with open(os.path.join(out_dir, "suite_config.json"), "w", encoding="utf-8") as f:
        json.dump(dict(n=n, seed=seed, variants=variants, base=base, clips=[dict(name=a, config=c) for a, c, _, _ in tasks]),
                  f, indent=1)
    rows: dict = {}
    idx_path = os.path.join(out_dir, "index.csv")

    def done(row: dict) -> None:
        rows[row["name"]] = row
        if progress:
            progress(f"[{len(rows)}/{n}] {row['name']}: {row['status']}"
                     + (f" ({row.get('gen_time_s')} s)" if row["status"] == "ok" else f" {row.get('error', '')}"))
        write_index([rows[t[0]] for t in tasks if t[0] in rows], idx_path)

    if jobs <= 1:
        for t in tasks:
            done(_suite_one(t))
    else:
        ctx = multiprocessing.get_context("spawn")
        with cf.ProcessPoolExecutor(max_workers=jobs, mp_context=ctx) as ex:
            futs = {ex.submit(_suite_one, t): t for t in tasks}
            for fut in cf.as_completed(futs):
                t = futs[fut]
                try:
                    done(fut.result())
                except Exception as e:        # noqa: BLE001 - e.g. a worker crashed
                    done(dict(name=t[0], status="error", file=os.path.basename(t[2]), error=f"{type(e).__name__}: {e}"))
    ordered = [rows[t[0]] for t in tasks]
    write_index(ordered, idx_path)
    return ordered


__all__ = ["suite_configs", "generate_suite", "write_index", "INDEX_COLUMNS", "calib_path_for"]
